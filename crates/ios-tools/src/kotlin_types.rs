//! The Kotlin mirrors of the values the phone bridge carries, generated from
//! the same Rust definitions as [`crate::swift_types`]:
//! `cargo run -p ios-tools -- kotlin-types` writes them and `--check` fails
//! when the committed files differ, so a hand edit or a Rust change without a
//! regeneration cannot land.
//!
//! The Rust values serialize with serde's defaults, and their schemas come
//! from schemars. A struct becomes a `@Serializable data class` (or a
//! `@Serializable class` with value equality when empty) with `@SerialName`
//! for each Rust field name; a string-only enum becomes a `@Serializable enum
//! class`; any other enum is serde's externally tagged form, `"Unit"` or
//! `{"Variant": ..}`, as a `sealed interface` with a generated `KSerializer`.
//! Any schema shape outside those fails the generation rather than producing a
//! mirror that decodes wrongly.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use serde_json::{Map, Value};

use crate::swift_types::{
    PUSH_VALUES, camel, definitions, description, upper_first, write_or_check,
};

/// The mirrors the push module reads without pulling in the rest of the value
/// vocabulary; `Values.kt` imports them from here. They are committed, and
/// `Values.kt` is not: the Android build writes it (`--values`).
pub const PUSH_OUTPUT: &str = "apps/android/push/src/main/kotlin/sh/amux/push/Said.kt";

const PACKAGE: &str = "sh.amux.values";
const PUSH_PACKAGE: &str = "sh.amux.push";

/// `kotlin-types [--check]`, run from anywhere in the repository, writes or
/// checks the committed push mirrors; `kotlin-types --values PATH` writes the
/// main mirrors to PATH, as the Android build does
/// (//apps/android/core/values).
pub fn main(args: &[String]) -> std::result::Result<(), Box<dyn std::error::Error>> {
    let check = match args {
        [] => false,
        [flag] if flag == "--check" => true,
        [flag, path] if flag == "--values" => {
            std::fs::write(path, generate(&definitions())?)?;
            return Ok(());
        }
        _ => return Err("usage: ios-tools kotlin-types [--check | --values PATH]".into()),
    };
    let files = [(PUSH_OUTPUT, generate_push(&definitions())?)];
    write_or_check("kotlin-types", &files, check)
}

type Result<T> = std::result::Result<T, String>;

const HEADER: &str = "// Generated by `cargo run -p ios-tools -- kotlin-types` from the Rust definitions of\n\
     // the values the phone bridge carries. Do not edit: change the Rust and\n\
     // regenerate; `--check` fails on any difference.\n\n";

/// Tracks which imports a generated file actually uses so Kotlin emits zero
/// unused-import warnings.
#[derive(Default)]
struct Imports {
    serial_name: bool,
    serializable: bool,
    tagged_enum: bool,
    json_primitive: bool,
    json_null: bool,
    build_json_object: bool,
    serializer_fn: bool,
    push_refs: BTreeSet<String>,
}

impl Imports {
    fn render(&self, package: &str) -> String {
        let mut lines = BTreeSet::new();
        if self.tagged_enum {
            lines.insert("kotlinx.serialization.KSerializer".to_owned());
            lines.insert("kotlinx.serialization.SerializationException".to_owned());
            lines.insert("kotlinx.serialization.descriptors.SerialDescriptor".to_owned());
            lines.insert("kotlinx.serialization.descriptors.buildClassSerialDescriptor".to_owned());
            lines.insert("kotlinx.serialization.encoding.Decoder".to_owned());
            lines.insert("kotlinx.serialization.encoding.Encoder".to_owned());
            lines.insert("kotlinx.serialization.json.JsonDecoder".to_owned());
            lines.insert("kotlinx.serialization.json.JsonElement".to_owned());
            lines.insert("kotlinx.serialization.json.JsonEncoder".to_owned());
            lines.insert("kotlinx.serialization.json.JsonObject".to_owned());
        }
        if self.serial_name {
            lines.insert("kotlinx.serialization.SerialName".to_owned());
        }
        if self.serializable {
            lines.insert("kotlinx.serialization.Serializable".to_owned());
        }
        if self.json_primitive {
            lines.insert("kotlinx.serialization.json.JsonPrimitive".to_owned());
        }
        if self.json_null {
            lines.insert("kotlinx.serialization.json.JsonNull".to_owned());
        }
        if self.build_json_object {
            lines.insert("kotlinx.serialization.json.buildJsonObject".to_owned());
        }
        if self.serializer_fn {
            lines.insert("kotlinx.serialization.serializer".to_owned());
        }
        if package != PUSH_PACKAGE {
            for name in &self.push_refs {
                lines.insert(format!("{PUSH_PACKAGE}.{name}"));
            }
        }
        let mut out = String::new();
        for line in lines {
            let _ = writeln!(out, "import {line}");
        }
        out
    }
}

struct FileContext<'a> {
    package: &'a str,
    is_push: bool,
    all_names: BTreeSet<&'a str>,
    imports: Imports,
}

impl<'a> FileContext<'a> {
    fn new(package: &'a str, is_push: bool, definitions: &'a Map<String, Value>) -> Self {
        Self {
            package,
            is_push,
            all_names: definitions.keys().map(String::as_str).collect(),
            imports: Imports::default(),
        }
    }

    fn resolve_ref(
        &mut self,
        owner: &str,
        reference: &str,
        shadowed: &BTreeSet<String>,
    ) -> Result<String> {
        let target = reference
            .strip_prefix("#/$defs/")
            .ok_or_else(|| format!("{owner}: an unsupported reference {reference}"))?;
        let target_is_push = PUSH_VALUES.contains(&target);
        if self.is_push && !target_is_push {
            return Err(format!(
                "{owner}: push value references non-push type {target}"
            ));
        }
        if shadowed.contains(target) {
            let pkg = if target_is_push {
                PUSH_PACKAGE
            } else {
                PACKAGE
            };
            Ok(format!("{pkg}.{target}"))
        } else {
            if !self.is_push && target_is_push {
                self.imports.push_refs.insert(target.to_owned());
            }
            Ok(target.to_owned())
        }
    }
}

/// The Kotlin source for every definition except the push values, sorted by name.
pub fn generate(definitions: &Map<String, Value>) -> Result<String> {
    let names = definitions
        .keys()
        .filter(|name| !PUSH_VALUES.contains(&name.as_str()))
        .collect();
    declarations(definitions, names, PACKAGE, false)
}

/// The Kotlin source for the push values, sorted by name.
pub fn generate_push(definitions: &Map<String, Value>) -> Result<String> {
    let names = definitions
        .keys()
        .filter(|name| PUSH_VALUES.contains(&name.as_str()))
        .collect();
    declarations(definitions, names, PUSH_PACKAGE, true)
}

fn declarations(
    definitions: &Map<String, Value>,
    names: BTreeSet<&String>,
    package: &str,
    is_push: bool,
) -> Result<String> {
    let mut ctx = FileContext::new(package, is_push, definitions);
    let mut body = String::new();
    for name in names {
        let schema = &definitions[name.as_str()];
        body.push('\n');
        body.push_str(&declaration(name, schema, &mut ctx)?);
    }
    let imports = ctx.imports.render(package);
    let mut out = format!("{HEADER}package {package}\n");
    if !imports.is_empty() {
        out.push('\n');
        out.push_str(&imports);
    }
    out.push_str(&body);
    Ok(out)
}

fn declaration(name: &str, schema: &Value, ctx: &mut FileContext<'_>) -> Result<String> {
    let doc = docs(schema, "");
    if let Some(variants) = schema.get("oneOf").and_then(Value::as_array) {
        return Ok(doc + &tagged_enum(name, variants, ctx)?);
    }
    match schema.get("type").and_then(Value::as_str) {
        Some("object") => Ok(doc + &structure(name, schema, ctx)?),
        Some("string") => {
            let cases = schema
                .get("enum")
                .and_then(Value::as_array)
                .ok_or_else(|| format!("{name}: a string schema without cases"))?;
            let cases = cases
                .iter()
                .map(|case| {
                    case.as_str()
                        .map(|case| (case.to_owned(), None))
                        .ok_or_else(|| format!("{name}: a case that is not a string"))
                })
                .collect::<Result<Vec<_>>>()?;
            Ok(doc + &string_enum(name, &cases, ctx)?)
        }
        _ => Err(format!("{name}: an unsupported schema {schema}")),
    }
}

// --- structs ---------------------------------------------------------------

/// A property as Kotlin declares it.
struct Field {
    json: String,
    kotlin: String,
    /// Non-nullable base type (e.g. `String`, `Int`, `List<Int>`).
    base_ty: String,
    /// Unqualified non-nullable base type for top-level serializer code.
    serializer_ty: String,
    optional: bool,
    doc: String,
}

impl Field {
    fn full_ty(&self) -> String {
        if self.optional {
            format!("{}?", self.base_ty)
        } else {
            self.base_ty.clone()
        }
    }
}

/// The object's properties: required ones in declaration order, then the
/// rest by name. An optional property is nullable with default `= null`.
fn fields(
    owner: &str,
    schema: &Value,
    shadowed: &BTreeSet<String>,
    ctx: &mut FileContext<'_>,
) -> Result<Vec<Field>> {
    let empty = Map::new();
    let properties = schema
        .get("properties")
        .and_then(Value::as_object)
        .unwrap_or(&empty);
    let required: Vec<&str> = schema
        .get("required")
        .and_then(Value::as_array)
        .map(|names| names.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    let mut order: Vec<&str> = required.clone();
    order.extend(
        properties
            .keys()
            .map(String::as_str)
            .filter(|name| !required.contains(name)),
    );
    let no_shadow = BTreeSet::new();
    let mut seen = BTreeSet::new();
    order
        .into_iter()
        .map(|json| {
            let property = properties
                .get(json)
                .ok_or_else(|| format!("{owner}: {json} is required but has no schema"))?;
            let (base_ty, nullable) = kotlin_type(owner, property, shadowed, ctx)?;
            let (serializer_ty, _) = if shadowed.is_empty() {
                (base_ty.clone(), nullable)
            } else {
                kotlin_type(owner, property, &no_shadow, ctx)?
            };
            let optional = nullable || !required.contains(&json);
            let kotlin = identifier(&camel_ident(json));
            if !seen.insert(kotlin.clone()) {
                return Err(format!("{owner}: duplicate Kotlin field name {kotlin}"));
            }
            Ok(Field {
                json: json.to_owned(),
                kotlin,
                base_ty,
                serializer_ty,
                optional,
                doc: docs(property, "    "),
            })
        })
        .collect()
}

fn structure(name: &str, schema: &Value, ctx: &mut FileContext<'_>) -> Result<String> {
    let empty_shadow = BTreeSet::new();
    let fields = fields(name, schema, &empty_shadow, ctx)?;
    for field in &fields {
        if !field.optional && field.base_ty == name {
            return Err(format!("{name} holds itself directly without optionality"));
        }
    }
    ctx.imports.serializable = true;
    if fields.is_empty() {
        // Kotlin forbids parameterless data classes; a regular @Serializable
        // class encodes/decodes as `{}` while keeping value equality.
        return Ok(format!(
            "@Serializable\n\
             class {name} {{\n    \
                 override fun equals(other: Any?): Boolean = other is {name}\n\n    \
                 override fun hashCode(): Int = 0\n\n    \
                 override fun toString(): String = \"{name}()\"\n\
             }}\n"
        ));
    }
    ctx.imports.serial_name = true;
    let mut out = format!("@Serializable\ndata class {name}(\n");
    for field in &fields {
        out.push_str(&field.doc);
        let default = if field.optional { " = null" } else { "" };
        let _ = writeln!(
            out,
            "    @SerialName(\"{}\") val {}: {}{default},",
            field.json,
            field.kotlin,
            field.full_ty()
        );
    }
    out.push_str(")\n");
    Ok(out)
}

// --- enums -----------------------------------------------------------------

fn string_enum(
    name: &str,
    cases: &[(String, Option<String>)],
    ctx: &mut FileContext<'_>,
) -> Result<String> {
    ctx.imports.serializable = true;
    ctx.imports.serial_name = true;
    let mut out = format!("@Serializable\nenum class {name} {{\n");
    let mut seen = BTreeSet::new();
    for (case, doc) in cases {
        if let Some(doc) = doc {
            out.push_str(&kdoc(doc, "    "));
        }
        let kotlin = pascal_ident(case);
        if !seen.insert(kotlin.clone()) {
            return Err(format!("{name}: duplicate Kotlin enum case {kotlin}"));
        }
        let _ = writeln!(out, "    @SerialName(\"{case}\")");
        let _ = writeln!(out, "    {kotlin},");
    }
    out.push_str("}\n");
    Ok(out)
}

/// What a tagged enum variant carries.
enum Payload {
    Unit,
    /// A newtype variant: one value of this Kotlin type.
    Value {
        base_ty: String,
        serializer_ty: String,
        nullable: bool,
    },
    /// A struct variant: named fields.
    Fields(Vec<Field>),
}

struct Variant {
    json: String,
    kotlin: String,
    doc: String,
    payload: Payload,
}

fn raw_variant_names(name: &str, schemas: &[Value]) -> Result<BTreeSet<String>> {
    let mut names = BTreeSet::new();
    names.insert(name.to_owned());
    for schema in schemas {
        if let Some(case) = schema.get("const").and_then(Value::as_str) {
            names.insert(pascal_ident(case));
        } else if let Some(cases) = schema.get("enum").and_then(Value::as_array) {
            for case in cases {
                let case = case
                    .as_str()
                    .ok_or_else(|| format!("{name}: a case that is not a string"))?;
                names.insert(pascal_ident(case));
            }
        } else if schema.get("type").and_then(Value::as_str) == Some("object") {
            let properties = schema
                .get("properties")
                .and_then(Value::as_object)
                .filter(|properties| properties.len() == 1)
                .ok_or_else(|| format!("{name}: a variant that is not externally tagged"))?;
            let (json, _) = properties.iter().next().expect("one property");
            names.insert(pascal_ident(json));
        } else {
            return Err(format!("{name}: an unsupported variant {schema}"));
        }
    }
    Ok(names)
}

fn variants(name: &str, schemas: &[Value], ctx: &mut FileContext<'_>) -> Result<Vec<Variant>> {
    let shadowed = raw_variant_names(name, schemas)?;
    let no_shadow = BTreeSet::new();
    let mut out = Vec::new();
    let mut seen = BTreeSet::new();
    for schema in schemas {
        let doc = docs(schema, "    ");
        if let Some(case) = schema.get("const").and_then(Value::as_str) {
            let kotlin = pascal_ident(case);
            if !seen.insert(kotlin.clone()) {
                return Err(format!("{name}: duplicate Kotlin variant name {kotlin}"));
            }
            out.push(Variant {
                json: case.to_owned(),
                kotlin,
                doc,
                payload: Payload::Unit,
            });
        } else if let Some(cases) = schema.get("enum").and_then(Value::as_array) {
            for case in cases {
                let case = case
                    .as_str()
                    .ok_or_else(|| format!("{name}: a case that is not a string"))?;
                let kotlin = pascal_ident(case);
                if !seen.insert(kotlin.clone()) {
                    return Err(format!("{name}: duplicate Kotlin variant name {kotlin}"));
                }
                out.push(Variant {
                    json: case.to_owned(),
                    kotlin,
                    doc: doc.clone(),
                    payload: Payload::Unit,
                });
            }
        } else if schema.get("type").and_then(Value::as_str) == Some("object") {
            let properties = schema
                .get("properties")
                .and_then(Value::as_object)
                .filter(|properties| properties.len() == 1)
                .ok_or_else(|| format!("{name}: a variant that is not externally tagged"))?;
            let (json, payload) = properties.iter().next().expect("one property");
            let owner = format!("{name}.{json}");
            let payload = if payload.get("type").and_then(Value::as_str) == Some("object")
                && payload.get("properties").is_some()
            {
                Payload::Fields(fields(&owner, payload, &shadowed, ctx)?)
            } else {
                let (base_ty, nullable) = kotlin_type(&owner, payload, &shadowed, ctx)?;
                let (serializer_ty, _) = kotlin_type(&owner, payload, &no_shadow, ctx)?;
                Payload::Value {
                    base_ty,
                    serializer_ty,
                    nullable,
                }
            };
            let kotlin = pascal_ident(json);
            if !seen.insert(kotlin.clone()) {
                return Err(format!("{name}: duplicate Kotlin variant name {kotlin}"));
            }
            out.push(Variant {
                json: json.clone(),
                kotlin,
                doc,
                payload,
            });
        } else {
            return Err(format!("{name}: an unsupported variant {schema}"));
        }
    }
    Ok(out)
}

fn tagged_enum(name: &str, schemas: &[Value], ctx: &mut FileContext<'_>) -> Result<String> {
    let variants = variants(name, schemas, ctx)?;
    if variants
        .iter()
        .all(|variant| matches!(variant.payload, Payload::Unit))
    {
        let cases: Vec<(String, Option<String>)> = variants
            .iter()
            .map(|variant| {
                let doc = (!variant.doc.is_empty()).then(|| unkdoc(&variant.doc));
                (variant.json.clone(), doc)
            })
            .collect();
        return string_enum(name, &cases, ctx);
    }

    let serializer_name = format!("{name}Serializer");
    if ctx.all_names.contains(serializer_name.as_str()) {
        return Err(format!(
            "{name}: generated serializer name {serializer_name} collides with another type"
        ));
    }

    ctx.imports.serializable = true;
    ctx.imports.tagged_enum = true;

    let mut out =
        format!("@Serializable(with = {serializer_name}::class)\nsealed interface {name} {{\n");
    // If any nested variant shares the enclosing sealed interface's name
    // (e.g. `Installed.Installed`), Kotlin resolves unqualified `Installed`
    // inside the interface body to that nested class rather than the outer
    // interface, so every variant must qualify the supertype with the package.
    let self_shadowed = variants.iter().any(|variant| variant.kotlin == name);
    let supertype = if self_shadowed {
        format!("{}.{name}", ctx.package)
    } else {
        name.to_owned()
    };
    for variant in &variants {
        out.push_str(&variant.doc);
        match &variant.payload {
            Payload::Unit => {
                let _ = writeln!(out, "    data object {} : {supertype}", variant.kotlin);
            }
            Payload::Value {
                base_ty, nullable, ..
            } => {
                let (ty, default) = if *nullable {
                    (format!("{base_ty}?"), " = null")
                } else {
                    (base_ty.clone(), "")
                };
                let _ = writeln!(
                    out,
                    "    data class {}(val value: {ty}{default}) : {supertype}",
                    variant.kotlin
                );
            }
            Payload::Fields(fields) if fields.is_empty() => {
                let _ = writeln!(out, "    data object {} : {supertype}", variant.kotlin);
            }
            Payload::Fields(fields) => {
                let _ = writeln!(out, "    data class {}(", variant.kotlin);
                for field in fields {
                    let default = if field.optional { " = null" } else { "" };
                    let _ = writeln!(
                        out,
                        "        val {}: {}{default},",
                        field.kotlin,
                        field.full_ty()
                    );
                }
                let _ = writeln!(out, "    ) : {supertype}");
            }
        }
    }
    out.push_str("}\n\n");

    let tagged: Vec<&Variant> = variants
        .iter()
        .filter(|variant| !matches!(variant.payload, Payload::Unit))
        .collect();
    let units: Vec<&Variant> = variants
        .iter()
        .filter(|variant| matches!(variant.payload, Payload::Unit))
        .collect();

    if !units.is_empty() {
        ctx.imports.json_primitive = true;
    }

    let uses_json_codec = tagged.iter().any(|variant| match &variant.payload {
        Payload::Unit => false,
        Payload::Value { .. } => true,
        Payload::Fields(fields) => !fields.is_empty(),
    });
    if uses_json_codec {
        ctx.imports.serializer_fn = true;
    }

    let _ = writeln!(out, "object {serializer_name} : KSerializer<{name}> {{");
    let _ = writeln!(
        out,
        "    override val descriptor: SerialDescriptor =\n        \
         buildClassSerialDescriptor(\"{}.{name}\")\n",
        ctx.package
    );

    // --- deserialize ---
    let _ = writeln!(
        out,
        "    override fun deserialize(decoder: Decoder): {name} {{"
    );
    let _ = writeln!(
        out,
        "        val jsonDecoder = decoder as? JsonDecoder\n            \
         ?: throw SerializationException(\"{name} requires Json\")"
    );
    out.push_str("        val element = jsonDecoder.decodeJsonElement()\n");
    if !units.is_empty() {
        out.push_str("        if (element is JsonPrimitive && element.isString) {\n");
        out.push_str("            return when (element.content) {\n");
        for variant in &units {
            let _ = writeln!(
                out,
                "                \"{}\" -> {name}.{}",
                variant.json, variant.kotlin
            );
        }
        let _ = writeln!(
            out,
            "                else -> throw SerializationException(\"no {name} is named ${{element.content}}\")"
        );
        out.push_str("            }\n        }\n");
    }
    let expected = if units.is_empty() {
        "an object"
    } else {
        "a string or object"
    };
    let _ = writeln!(
        out,
        "        val obj = element as? JsonObject\n            \
         ?: throw SerializationException(\"{name} must be {expected}\")"
    );
    let _ = writeln!(
        out,
        "        if (obj.size != 1) {{\n            \
         throw SerializationException(\"{name} names exactly one variant\")\n        }}"
    );
    out.push_str("        val (tag, payload) = obj.entries.first()\n");
    if uses_json_codec {
        out.push_str("        val json = jsonDecoder.json\n");
    }
    out.push_str("        return when (tag) {\n");
    for variant in &tagged {
        match &variant.payload {
            Payload::Unit => unreachable!("filtered"),
            Payload::Value {
                serializer_ty,
                nullable: false,
                ..
            } => {
                let _ = writeln!(
                    out,
                    "            \"{}\" -> {name}.{}(json.decodeFromJsonElement(serializer<{serializer_ty}>(), payload))",
                    variant.json, variant.kotlin
                );
            }
            Payload::Value {
                serializer_ty,
                nullable: true,
                ..
            } => {
                ctx.imports.json_null = true;
                let _ = writeln!(
                    out,
                    "            \"{}\" -> {name}.{}(\n                \
                     if (payload is JsonNull) null else json.decodeFromJsonElement(serializer<{serializer_ty}>(), payload),\n            )",
                    variant.json, variant.kotlin
                );
            }
            Payload::Fields(fields) if fields.is_empty() => {
                let _ = writeln!(
                    out,
                    "            \"{}\" -> {{\n                \
                     if (payload !is JsonObject) {{\n                    \
                     throw SerializationException(\"{name}.{} payload must be an object\")\n                \
                     }}\n                \
                     {name}.{}\n            }}",
                    variant.json, variant.kotlin, variant.kotlin
                );
            }
            Payload::Fields(fields) => {
                let _ = writeln!(out, "            \"{}\" -> {{", variant.json);
                let _ = writeln!(
                    out,
                    "                val fields = payload as? JsonObject\n                    \
                     ?: throw SerializationException(\"{name}.{} payload must be an object\")",
                    variant.kotlin
                );
                let _ = writeln!(out, "                {name}.{}(", variant.kotlin);
                for field in fields {
                    if field.optional {
                        ctx.imports.json_null = true;
                        let _ = writeln!(
                            out,
                            "                    {} = fields[\"{}\"]?.takeUnless {{ it is JsonNull }}?.let {{\n                        \
                             json.decodeFromJsonElement(serializer<{}>(), it)\n                    }},",
                            field.kotlin, field.json, field.serializer_ty
                        );
                    } else {
                        let _ = writeln!(
                            out,
                            "                    {} = json.decodeFromJsonElement(\n                        \
                             serializer<{}>(),\n                        \
                             fields[\"{}\"] ?: throw SerializationException(\"{name}.{} missing field {}\"),\n                    ),",
                            field.kotlin,
                            field.serializer_ty,
                            field.json,
                            variant.kotlin,
                            field.json
                        );
                    }
                }
                out.push_str("                )\n            }\n");
            }
        }
    }
    let _ = writeln!(
        out,
        "            else -> throw SerializationException(\"unknown {name} variant $tag\")"
    );
    out.push_str("        }\n    }\n\n");

    // --- serialize ---
    let _ = writeln!(
        out,
        "    override fun serialize(encoder: Encoder, value: {name}) {{"
    );
    let _ = writeln!(
        out,
        "        val jsonEncoder = encoder as? JsonEncoder\n            \
         ?: throw SerializationException(\"{name} requires Json\")"
    );
    if uses_json_codec {
        out.push_str("        val json = jsonEncoder.json\n");
    }
    out.push_str("        val element: JsonElement = when (value) {\n");
    for variant in &variants {
        match &variant.payload {
            Payload::Unit => {
                let _ = writeln!(
                    out,
                    "            {name}.{} -> JsonPrimitive(\"{}\")",
                    variant.kotlin, variant.json
                );
            }
            // Always emit the tag key, even when a newtype payload is null:
            // serde requires `{"Model": null}`, never `{}`.
            Payload::Value {
                serializer_ty,
                nullable: false,
                ..
            } => {
                let _ = writeln!(
                    out,
                    "            is {name}.{} -> JsonObject(\n                \
                     mapOf(\"{}\" to json.encodeToJsonElement(serializer<{serializer_ty}>(), value.value)),\n            )",
                    variant.kotlin, variant.json
                );
            }
            Payload::Value {
                serializer_ty,
                nullable: true,
                ..
            } => {
                ctx.imports.json_null = true;
                let _ = writeln!(
                    out,
                    "            is {name}.{} -> JsonObject(\n                \
                     mapOf(\n                    \
                     \"{}\" to (\n                        \
                     value.value?.let {{ json.encodeToJsonElement(serializer<{serializer_ty}>(), it) }}\n                            \
                     ?: JsonNull\n                    ),\n                ),\n            )",
                    variant.kotlin, variant.json
                );
            }
            Payload::Fields(fields) if fields.is_empty() => {
                let _ = writeln!(
                    out,
                    "            {name}.{} -> JsonObject(mapOf(\"{}\" to JsonObject(emptyMap())))",
                    variant.kotlin, variant.json
                );
            }
            Payload::Fields(fields) => {
                ctx.imports.build_json_object = true;
                let _ = writeln!(
                    out,
                    "            is {name}.{} -> JsonObject(\n                \
                     mapOf(\n                    \
                     \"{}\" to buildJsonObject {{",
                    variant.kotlin, variant.json
                );
                for field in fields {
                    if field.optional {
                        let _ = writeln!(
                            out,
                            "                        value.{}?.let {{\n                            \
                             put(\"{}\", json.encodeToJsonElement(serializer<{}>(), it))\n                        }}",
                            field.kotlin, field.json, field.serializer_ty
                        );
                    } else {
                        let _ = writeln!(
                            out,
                            "                        put(\"{}\", json.encodeToJsonElement(serializer<{}>(), value.{}))",
                            field.json, field.serializer_ty, field.kotlin
                        );
                    }
                }
                out.push_str("                    },\n                ),\n            )\n");
            }
        }
    }
    out.push_str("        }\n        jsonEncoder.encodeJsonElement(element)\n    }\n}\n");
    Ok(out)
}

