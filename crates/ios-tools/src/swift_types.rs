    /// mirror, except the ones that never cross it.
    #[test]
    fn every_public_view_value_has_a_swift_mirror() {
        const STAY_IN_RUST: &[&str] = &[
            // The answer body a choice sends: the phone names the choice.
            "Answer",
            // Borrowed option types; the chat holds its own open runs.
            "ToolRows",
            "ChatOptions",
            // A landed edit's first patch lines, which only the terminal
            // draws: ui_view::patch_head is called by no bridge function.
            "PatchHead",
            // What a session knows for its fleet row: the runtime reads it
            // and hands it to ui_view::fleet_view, which returns the cards
            // the phone draws.
            "SessionLine",
            // What a typed draft is to the terminal; the phone asks the
            // bridge's command call, which answers a CommandOutcome.
            "Slash",
        ];
        let definitions = definitions();
        let root = repository();
        let mut missing = Vec::new();
        for dir in [
            "crates/model/src",
            "crates/ui-view/src",
            "crates/app-runtime/src/values.rs",
        ] {
            let path = root.join(dir);
            let files = if path.is_dir() {
                std::fs::read_dir(&path)
                    .unwrap()
                    .map(|entry| entry.unwrap().path())
                    .collect()
            } else {
                vec![path]
            };
            for file in files {
                let text = std::fs::read_to_string(&file).unwrap();
                for line in text.lines() {
                    let line = line.trim_start();
                    let Some(rest) = line
                        .strip_prefix("pub struct ")
                        .or_else(|| line.strip_prefix("pub enum "))
                    else {
                        continue;
                    };
                    let name: String = rest
                        .chars()
                        .take_while(|c| c.is_alphanumeric() || *c == '_')
                        .collect();
                    if !STAY_IN_RUST.contains(&name.as_str()) && !definitions.contains_key(&name) {
                        missing.push(format!("{name} ({})", file.display()));
                    }
                }
            }
        }
        assert!(missing.is_empty(), "no Swift mirror for: {missing:#?}");
    }

    #[test]
    fn a_shape_swift_cannot_mirror_fails_the_generation() {
        let tuple = json!({"T": {"type": "object", "properties": {
            "pair": {"type": "array", "prefixItems": [{"type": "string"}, {"type": "number"}]}
        }, "required": ["pair"]}});
        let error = generate(tuple.as_object().unwrap()).unwrap_err();
        assert!(error.contains("tuple"), "{error}");
        let untagged = json!({"U": {"oneOf": [{"type": "object", "properties": {
            "a": {"type": "string"}, "b": {"type": "string"}
        }}]}});
        assert!(generate(untagged.as_object().unwrap()).is_err());
    }

    #[test]
    fn names_follow_swift_and_keep_the_rust_keys() {
        let schema = json!({"S": {"type": "object", "properties": {
            "max_attempts": {"type": "integer", "format": "uint32"},
            "default": {"type": ["string", "null"]}
        }, "required": ["max_attempts"]}});
        let swift = generate(schema.as_object().unwrap()).unwrap();
        assert!(swift.contains("public var maxAttempts: UInt32"), "{swift}");
        assert!(
            swift.contains("case maxAttempts = \"max_attempts\""),
            "{swift}"
        );
        assert!(swift.contains("public var `default`: String?"), "{swift}");
    }
