    #[test]
    fn empty_struct_and_shadowed_variants_emit_valid_kotlin() {
        let defs = definitions();
        let main_kt = generate(&defs).unwrap();
        let push_kt = generate_push(&defs).unwrap();

        // An empty struct is a regular @Serializable class (not the invalid
        // `data class Empty()`). No value the bridge hands over is empty now,
        // so the struct is one of its own.
        let mut lone = Map::new();
        lone.insert(
            "Empty".to_owned(),
            json!({"type": "object", "properties": {}}),
        );
        let empty_kt = generate(&lone).unwrap();
        assert!(
            empty_kt.contains("@Serializable\nclass Empty {"),
            "{empty_kt}"
        );
        assert!(!empty_kt.contains("data class Empty("));

        // Self-named variant qualifies supertype on every variant of the
        // enclosing sealed interface so the nested class never shadows it.
        assert!(
            main_kt.contains("data object Running : sh.amux.values.Installed"),
            "Installed.Running supertype must be package-qualified"
        );
        assert!(
            main_kt.contains("data object Started : sh.amux.values.Installed"),
            "Installed.Started supertype must be package-qualified"
        );
        assert!(
            main_kt.contains("data class Installed(\n        val version: String,\n    ) : sh.amux.values.Installed"),
            "Installed.Installed supertype must be package-qualified"
        );

        // A variant named `List` leaves Kotlin's own list qualified inside
        // its sealed interface.
        assert!(
            main_kt.contains("val items: kotlin.collections.List<ProseItem>,\n    ) : ProseBlock"),
            "ProseBlock.List must qualify kotlin.collections.List"
        );

        // Shadowed external/peer types inside sealed interface variants are package-qualified.
        assert!(
            main_kt.contains("data class Said(val value: sh.amux.push.Said) : SecondLine"),
            "SecondLine.Said must qualify sh.amux.push.Said"
        );
        assert!(
            main_kt.contains("data class Waiting(val value: sh.amux.values.Waiting) : Composer"),
            "Composer.Waiting must qualify sh.amux.values.Waiting"
        );
        assert!(
            main_kt.contains("data class Offline(val value: sh.amux.values.Offline) : Reach"),
            "Reach.Offline must qualify sh.amux.values.Offline"
        );

        // Nullable newtype payload explicitly emits JsonNull on serialize.
        assert!(
            main_kt.contains("\"Model\" to (\n                        value.value?.let { json.encodeToJsonElement(serializer<String>(), it) }\n                            ?: JsonNull"),
            "NewAgentPick.Model must write explicit JsonNull when null"
        );

        // Snake-case string enum maps to PascalCase entries with @SerialName.
        assert!(
            main_kt.contains("@SerialName(\"pair_phone\")\n    PairPhone,"),
            "SetupStep should use PascalCase entries"
        );

        // Push file imports no unused SerialName and lives in sh.amux.push.
        assert!(push_kt.contains("package sh.amux.push\n"));
        assert!(!push_kt.contains("SerialName"));
        assert!(main_kt.contains("import sh.amux.push.Said\n"));
        assert!(!main_kt.contains("import sh.amux.push.Wants\n"));
    }

    #[test]
    fn generated_serializers_match_rust_serde_wire_shapes() {
        let defs = definitions();
        let main_kt = generate(&defs).unwrap();
        let push_kt = generate_push(&defs).unwrap();

        // Unit variants serialize as bare JSON strings.
        assert_eq!(
            serde_json::to_value(app_runtime::values::ActOutcome::Done).unwrap(),
            json!("Done")
        );
        assert!(main_kt.contains("ActOutcome.Done -> JsonPrimitive(\"Done\")"));

        assert_eq!(
            serde_json::to_value(wire::Said::SignedOut).unwrap(),
            json!("SignedOut")
        );
        assert!(push_kt.contains("Said.SignedOut -> JsonPrimitive(\"SignedOut\")"));

        // Nullable newtype variants serialize as `{"Variant": null}` on None.
        assert_eq!(
            serde_json::to_value(ui_view::NewAgentPick::Model(None)).unwrap(),
            json!({"Model": null})
        );
        assert_eq!(
            serde_json::to_value(ui_view::NewAgentPick::Model(Some("sonnet".into()))).unwrap(),
            json!({"Model": "sonnet"})
        );
        // Rust accepts explicit null for nullable newtype variants.
        assert_eq!(
            serde_json::from_value::<ui_view::NewAgentPick>(json!({"Model": null})).unwrap(),
            ui_view::NewAgentPick::Model(None)
        );
        assert!(main_kt.contains("if (payload is JsonNull) null else json.decodeFromJsonElement(serializer<String>(), payload)"));

        // Struct variants with optional fields: Rust emits explicit null for
        // `Option<T>`, while `#[serde(default)]` non-Option fields like
        // `PairRequest::Pin::host_id` require omitting the key when unset
        // (matching Kotlin's `?.let { put(...) }`).
        assert_eq!(
            serde_json::to_value(wire::Said::UsageLimit { resets_at_ms: None }).unwrap(),
            json!({"UsageLimit": {"resets_at_ms": null}})
        );
        assert!(
            push_kt.contains(
                "resetsAtMs = fields[\"resets_at_ms\"]?.takeUnless { it is JsonNull }?.let"
            )
        );
        assert_eq!(
            serde_json::from_value::<app_runtime::values::PairRequest>(
                json!({"Pin": {"pin": "123456", "addrs": []}})
            )
            .unwrap(),
            app_runtime::values::PairRequest::Pin {
                pin: "123456".into(),
                addrs: vec![],
                host_id: vec![],
            }
        );
        assert!(
            serde_json::from_value::<app_runtime::values::PairRequest>(
                json!({"Pin": {"pin": "123456", "addrs": [], "host_id": null}})
            )
            .is_err()
        );
        assert!(main_kt.contains("value.hostId?.let {"));

        // Empty structs serialize and deserialize as `{}`.
        assert_eq!(serde_json::to_value(wire::Empty {}).unwrap(), json!({}));
        assert_eq!(
            serde_json::from_value::<wire::Empty>(json!({})).unwrap(),
            wire::Empty {}
        );

        // Snake-case string enums keep exact wire names.
        assert_eq!(
            serde_json::to_value(ui_view::SetupStep::PairPhone).unwrap(),
            json!("pair_phone")
        );
        assert!(main_kt.contains("@SerialName(\"pair_phone\")\n    PairPhone,"));

        // Byte vectors serialize as JSON integer arrays matching `List<Int>`.
        assert_eq!(
            serde_json::to_value(app_runtime::values::ChatAct::Withdraw(vec![1, 2, 255])).unwrap(),
            json!({"Withdraw": [1, 2, 255]})
        );
        assert!(main_kt.contains("data class Withdraw(val value: List<Int>) : ChatAct"));
    }
