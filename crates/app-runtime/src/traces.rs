//! The client model's schedules as the phone's chat model reads them.
//!
//! The phone's chat model is the one second implementation of how a chat's
//! rows move: it keeps its own sequence of keys and its own cells, and reads
//! the runtime only at their edges and for the keys a change names. These
//! traces hold it equal to the Rust session. Each walks a schedule of the
//! client model (`models::client`) and, at every cut, writes what the
//! runtime would answer the phone then: the changes gathered since the last
//! cut as [`Chat::take_changes`](crate::Chat::take_changes) coalesces them,
//! the held keys, the rows for every key under the options the phone reads
//! with, and the frame. The Swift test `ChatModelTraceTests` replays them
//! through the chat model and asserts the same keys and rows at every cut.
//!
//! The fixtures are written only by `just client-traces`. The test here
//! fails when they no longer match the client model, so a change to the
//! model or the views is reviewed as a fixture diff, never regenerated by a
//! test run.

use std::collections::{BTreeSet, HashMap, HashSet};
use std::path::{Path, PathBuf};

use models::client::Action;
use models::{Bounds, ClientModel, Machine};
use serde::Serialize;
use ui_state::{InputOutcome, Key, Msg, SessionState};
use ui_view::{ChatOptions, Row, ToolRows};
use wire::session_event::Of;

use crate::values::{ChatChanges, ChatFrame};

/// The schedules recorded, one per seed.
const SEEDS: u64 = 12;
/// The most actions a schedule takes.
const DEPTH: usize = 40;
/// How many actions pass between the phone's wakes, by seed: every action
/// on even seeds, and three at a time on odd ones, so a wake also takes
/// several moves coalesced, as a busy phone does.
fn every(seed: u64) -> usize {
    if seed.is_multiple_of(2) { 1 } else { 3 }
}

/// One schedule as the phone reads it.
#[derive(Serialize)]
struct Trace {
    seed: u64,
    every: usize,
    cuts: Vec<Cut>,
}

/// What the runtime answers the phone at one wake.
#[derive(Serialize)]
struct Cut {
    /// The model's actions since the last cut.
    actions: Vec<String>,
    /// The messages they fed the session, in order.
    messages: Vec<String>,
    changes: ChatChanges,
    /// The held window's keys, oldest first.
    keys: Vec<Key>,
    /// The row for every held key, in order, as the phone asks for rows:
    /// runs folded with none open.
    rows: Vec<Row>,
    frame: ChatFrame,
}

fn fixtures() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../apps/apple/Packages/AmuxCore/Tests/AmuxCoreTests/Fixtures/client-traces")
}

fn file(seed: u64) -> String {
    format!("seed-{seed:02}.json")
}

/// Every trace, by file name, as JSON.
fn record() -> Vec<(String, String)> {
    (0..SEEDS)
        .map(|seed| {
            let trace = trace(seed);
            let json = serde_json::to_string_pretty(&trace).expect("a trace serializes") + "\n";
            (file(seed), json)
        })
        .collect()
}

fn trace(seed: u64) -> Trace {
    let model = ClientModel::ci();
    let walk = models::walk(&model, Bounds::depth(DEPTH), seed);
    assert!(walk.failure.is_none(), "{walk}");
    let mut state = model.init();
    // The runtime's session, fed what the model fed its client: the outcomes
    // of its updates are the changes the phone is woken with.
    let mut session = state.client().clone();
    let mut first_drawn = HashMap::new();
    let mut cuts = vec![cut(
        &session,
        &mut first_drawn,
        Vec::new(),
        Vec::new(),
        ChatChanges::default(),
    )];
    for actions in walk.actions.chunks(every(seed)) {
        let mut messages = Vec::new();
        let mut changes = ChatChanges::default();
        let mut seen = BTreeSet::new();
        for action in actions {
            state = model.next(&state, action).expect("a walked action applies");
            for msg in state.fed() {
                messages.push(describe(msg));
                let outcome = session.update(msg.clone());
                for key in outcome.changed {
                    if seen.insert(key.clone()) {
                        changes.keys.push(key);
                    }
                }
                changes.reloaded |= outcome.reloaded;
                changes.session |= outcome.session;
            }
            assert!(
                session == *state.client(),
                "seed {seed}: the session fed what the model fed its client differs from it"
            );
        }
        let actions = actions.iter().map(name).collect();
        cuts.push(cut(&session, &mut first_drawn, actions, messages, changes));
    }
    Trace {
        seed,
        every: every(seed),
        cuts,
    }
}

fn cut(
    session: &SessionState,
    first_drawn: &mut HashMap<Vec<u8>, bool>,
    actions: Vec<String>,
    messages: Vec<String>,
    changes: ChatChanges,
) -> Cut {
    let keys: Vec<Key> = session.transcript().keys().cloned().collect();
    let open = HashSet::new();
    let rows = ui_view::chat_rows_for(
        session,
        &keys,
        &ChatOptions {
            tools: ToolRows::Collapse { open: &open },
        },
    );
    super::chat::note_drawn(session, first_drawn);
    let frame = super::chat::frame(session, 0, None, first_drawn);
    Cut {
        actions,
        messages,
        changes,
        keys,
        rows,
        frame,
    }
}

fn name(action: &Action) -> String {
    format!("{action:?}")
}

/// A message as a person reads a trace: the event and the keys, revisions
/// and markers it carries.
fn describe(msg: &Msg) -> String {
    match msg {
        Msg::Event(event) => match &event.of {
            Some(Of::Opening(opening)) => format!("Opening generation {}", opening.generation),
            Some(Of::Reset(reset)) => format!("Reset generation {}", reset.generation),
            Some(Of::Snapshot(snapshot)) => format!("Snapshot r{}", snapshot.revision),
            Some(Of::Item(item)) => format!("Item {}@r{} {:?}", item.key, item.revision, item.text),
            Some(Of::Append(append)) => format!(
                "Append {} r{}->r{} {:?}",
                append.key, append.base_revision, append.revision, append.text
            ),
            Some(Of::CaughtUp(caught_up)) => format!("CaughtUp r{}", caught_up.revision),
            Some(Of::Lagged(_)) => "Lagged".into(),
            other => format!("{other:?}"),
        },
        Msg::Page {
            items, exhausted, ..
        } => {
            let keys: Vec<&str> = items.iter().map(|item| item.key.as_str()).collect();
            format!("Page {keys:?} exhausted {exhausted}")
        }
        Msg::Connection(connection) => format!("Connection {connection:?}"),
        Msg::Send(_) => "Send the prompt".into(),
        Msg::Sent(_, InputOutcome::Lost) => "Sent: lost".into(),
        Msg::Sent(_, outcome) => format!("Sent: {outcome:?}"),
        Msg::Discard(_) => "Discard the prompt".into(),
        other => format!("{other:?}"),
    }
}

#[test]
fn the_phones_trace_fixtures_are_the_client_models_current_traces() {
    let recorded = record();
    let mut stale = Vec::new();
    for (name, json) in &recorded {
        let held = std::fs::read_to_string(fixtures().join(name)).unwrap_or_default();
        if &held != json {
            stale.push(name.clone());
        }
    }
    let mut held: Vec<String> = std::fs::read_dir(fixtures())
        .map(|entries| {
            entries
                .filter_map(|entry| entry.ok()?.file_name().into_string().ok())
                .collect()
        })
        .unwrap_or_default();
    held.sort();
    let mut expected: Vec<String> = recorded.into_iter().map(|(name, _)| name).collect();
    expected.sort();
    assert!(
        stale.is_empty() && held == expected,
        "the phone's client traces differ from the client model's ({stale:?} stale, {held:?} held \
         against {expected:?}): run `just client-traces` and review the diff"
    );
}

/// Writes the fixtures; `just client-traces` runs it.
#[test]
#[ignore = "writes the phone's trace fixtures: run by `just client-traces`"]
fn write_client_traces() {
    let dir = fixtures();
    if dir.exists() {
        std::fs::remove_dir_all(&dir).expect("the old traces are removed");
    }
    std::fs::create_dir_all(&dir).expect("the trace directory is made");
    for (name, json) in record() {
        std::fs::write(dir.join(&name), json).expect("a trace is written");
        println!("wrote {}", dir.join(name).display());
    }
}
